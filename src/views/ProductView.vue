<script>
import { addTocart, removeItem, isInCart, cartitemCount, cartTotal } from '@/store/cart.js'
import products from '@/data/products.json'

export default {
  name: 'ProductView',
  data() {
    return {
      currentIndex: 0,
      totalCards: 5,
      viewedId: 'panadol-pain-fever-500mg-x100'
    }
  },
  computed: {
    viewedProduct() {
      const found = products.find(p => p.id === this.viewedId)
      if (!found) {
        console.warn(`No product in products.json matches id "${this.viewedId}"`)
      }
      const product = found || products[0]
      const gallery = product.gallery || [product.image, product.image, product.image, product.image]
      return { ...product, gallery }
    },
    badgeCount() {
      return cartitemCount()
    },
    total() {
      return cartTotal()
    }
  },
  methods: {
    isInCart,
    scrollToIndex(index) {
      const carousel = this.$refs.carousel
      const card = carousel.children[0]
      if (!card) return
      const cardWidth = card.offsetWidth
      const gap = 16
      carousel.scrollTo({ left: index * (cardWidth + gap), behavior: 'smooth' })
      this.currentIndex = index
    },
    nextCard() {
      if (this.currentIndex < this.totalCards - 1) this.scrollToIndex(this.currentIndex + 1)
    },
    prevCard() {
      if (this.currentIndex > 0) this.scrollToIndex(this.currentIndex - 1)
    },
    goToCard(index) {
      this.scrollToIndex(index)
    },
    viewProduct(id) {
      this.viewedId = id
    },
    toggleCart(id) {
      if (isInCart(id)) {
        removeItem(id)
      } else {
        addTocart(products.find(p => p.id === id))
      }
    },
    goToCart() {
      this.$router.push('/cart')
    }
  }
}
